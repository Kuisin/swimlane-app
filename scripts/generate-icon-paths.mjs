#!/usr/bin/env node
/**
 * Generates packages/core/src/render-pure/icon-paths.js from lucide-react icon nodes.
 * Run: node scripts/generate-icon-paths.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const iconsDir = path.join(root, "node_modules/lucide-react/dist/esm/icons");
const registryPath = path.join(root, "packages/core/src/icon-registry.js");
const outPath = path.join(root, "packages/core/src/render-pure/icon-paths.js");

const registrySource = fs.readFileSync(registryPath, "utf8");
const iconNames = [...registrySource.matchAll(/^\s+"?([\w-]+)"?:\s*\w/mg)]
  .map((m) => m[1])
  .filter((name) => name !== "LUCIDE_ICONS");

/** lucide-react kebab file names differ from registry keys in a few cases. */
const FILE_ALIASES = {
  trash: "trash-2",
  share: "share-2",
  stop: "square",
  "bar-chart": "chart-column",
  "test-tube": "test-tube-diagonal",
  sliders: "sliders-horizontal",
  undo: "undo-2",
  redo: "redo-2",
  building: "building-2",
  "alert-triangle": "triangle-alert",
};

function iconFileName(name) {
  return (FILE_ALIASES[name] || name).replace(/_/g, "-") + ".mjs";
}

async function loadIconNode(name) {
  const file = path.join(iconsDir, iconFileName(name));
  if (!fs.existsSync(file)) {
    console.warn(`Missing lucide icon file for "${name}": ${file}`);
    return null;
  }
  const mod = await import(pathToFileURL(file).href);
  return mod.__iconNode || mod.default?.__iconNode || null;
}

const entries = [];
for (const name of iconNames) {
  const node = await loadIconNode(name);
  if (node) entries.push([name, node]);
}

const body = entries
  .map(([name, node]) => `  "${name}": ${JSON.stringify(node)},`)
  .join("\n");

const output = `/** Auto-generated by scripts/generate-icon-paths.mjs — do not edit manually. */
export const LUCIDE_ICON_NODES = {
${body}
};

export function getLucideIconNode(name) {
  return LUCIDE_ICON_NODES[name] || null;
}
`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, output);
console.log(`Wrote ${entries.length} icon paths to ${outPath}`);
